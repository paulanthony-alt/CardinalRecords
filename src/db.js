'use strict';
const path = require('node:path');
const fs = require('node:fs');
const { AsyncLocalStorage } = require('node:async_hooks');
const { Pool, Client, types } = require('pg');

const ROOT = path.join(__dirname, '..');

// `neon deploy` / `neon env pull` write DATABASE_URL into .env.local (or .env).
// On a host like Render the variables are set in its dashboard instead, and
// variables already in the environment always win over these files.
for (const file of ['.env.local', '.env']) {
  const p = path.join(ROOT, file);
  if (fs.existsSync(p)) process.loadEnvFile(p);
}

const DATABASE_URL = process.env.DATABASE_URL;
if (!DATABASE_URL) {
  console.error('[db] DATABASE_URL is not set. Run `neon deploy` (or `neon env pull`) to write it to .env.local, or set it in your host\'s environment.');
  process.exit(1);
}

// Uploaded audio still lives on local disk.
const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(ROOT, 'data'));
const UPLOAD_DIR = path.join(DATA_DIR, 'uploads');
fs.mkdirSync(UPLOAD_DIR, { recursive: true });

// Counts, sums and bigint columns come back as strings by default. Every value
// in this game (ids, money, ms timestamps) fits in a JS number, so parse them.
types.setTypeParser(types.builtins.INT8, (v) => Number(v));
types.setTypeParser(types.builtins.NUMERIC, (v) => Number(v));

// App traffic uses the pooled URL. Neon suspends idle computes, which can drop
// idle connections; the error handler keeps that from crashing the server.
const pool = new Pool({
  connectionString: DATABASE_URL,
  max: Number(process.env.PG_POOL_MAX) || 10,
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 15_000,
});
pool.on('error', (err) => console.error('[db] idle connection error:', err.message));

const SCHEMA = `
CREATE TABLE IF NOT EXISTS games (
  id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             TEXT    NOT NULL,
  status           TEXT    NOT NULL DEFAULT 'setup',   -- setup | active | showcase | archived
  duration_days    INTEGER NOT NULL,
  starting_balance BIGINT  NOT NULL DEFAULT 0,
  label_cut_pct    INTEGER NOT NULL DEFAULT 10,
  max_players      INTEGER NOT NULL DEFAULT 30,
  uploads_open     INTEGER NOT NULL DEFAULT 0,         -- Record Owners switch music uploads on and off
  started_at       BIGINT,
  ended_at         BIGINT,
  created_by       BIGINT,
  created_at       BIGINT  NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id           BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     TEXT    NOT NULL,
  pin          TEXT,                                   -- NULL until the player claims the account
  role         TEXT    NOT NULL CHECK (role IN ('owner', 'player')),
  game_id      BIGINT  REFERENCES games(id),
  display_name TEXT    NOT NULL,
  role_title   TEXT    NOT NULL DEFAULT '',
  bio          TEXT    NOT NULL DEFAULT '',
  color        TEXT,
  active       INTEGER NOT NULL DEFAULT 1,
  tutorial     TEXT    NOT NULL DEFAULT '{}',
  created_at   BIGINT  NOT NULL,
  last_seen    BIGINT
);
-- Usernames are case-insensitive: "BFreeds" and "bfreeds" are the same account.
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));

CREATE TABLE IF NOT EXISTS sessions (
  token      TEXT   PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL
);

-- Every money movement. user_id NULL = the label vault (label cut on completed deals).
CREATE TABLE IF NOT EXISTS ledger (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id     BIGINT NOT NULL REFERENCES games(id),
  user_id     BIGINT REFERENCES users(id),
  amount      BIGINT NOT NULL,
  kind        TEXT   NOT NULL,   -- advance | grant | fine | escrow_hold | escrow_refund | payment | label_fee
  contract_id BIGINT,
  memo        TEXT   NOT NULL DEFAULT '',
  created_by  BIGINT,
  created_at  BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS services (
  id              BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id         BIGINT  NOT NULL REFERENCES games(id),
  user_id         BIGINT  NOT NULL REFERENCES users(id),
  title           TEXT    NOT NULL,
  description     TEXT    NOT NULL DEFAULT '',
  category        TEXT    NOT NULL DEFAULT 'Other',
  price           BIGINT  NOT NULL,
  turnaround_days INTEGER NOT NULL DEFAULT 7,
  active          INTEGER NOT NULL DEFAULT 1,
  created_at      BIGINT  NOT NULL
);

-- offered -> (countered) -> review -> active -> delivered -> completed
-- side exits: declined, rejected, cancelled
CREATE TABLE IF NOT EXISTS contracts (
  id           BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id      BIGINT  NOT NULL REFERENCES games(id),
  buyer_id     BIGINT  NOT NULL REFERENCES users(id),
  seller_id    BIGINT  NOT NULL REFERENCES users(id),
  service_id   BIGINT  REFERENCES services(id),
  title        TEXT    NOT NULL,
  terms        TEXT    NOT NULL DEFAULT '',
  amount       BIGINT  NOT NULL,
  escrow       BIGINT  NOT NULL DEFAULT 0,
  due_days     INTEGER,
  status       TEXT    NOT NULL,
  rating       INTEGER,
  created_at   BIGINT  NOT NULL,
  updated_at   BIGINT  NOT NULL,
  approved_at  BIGINT,
  completed_at BIGINT
);

CREATE TABLE IF NOT EXISTS contract_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(id),
  actor_id    BIGINT,
  action      TEXT   NOT NULL,
  note        TEXT   NOT NULL DEFAULT '',
  amount      BIGINT,
  created_at  BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS feed (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id    BIGINT NOT NULL REFERENCES games(id),
  kind       TEXT   NOT NULL,
  actor_id   BIGINT,
  message    TEXT   NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS tracks (
  id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id     BIGINT  NOT NULL REFERENCES games(id),
  user_id     BIGINT  NOT NULL REFERENCES users(id),
  title       TEXT    NOT NULL,
  genre       TEXT    NOT NULL DEFAULT '',
  description TEXT    NOT NULL DEFAULT '',
  credits     TEXT    NOT NULL DEFAULT '',
  filename    TEXT    NOT NULL,
  mime        TEXT    NOT NULL,
  size        BIGINT  NOT NULL,
  plays       INTEGER NOT NULL DEFAULT 0,
  created_at  BIGINT  NOT NULL
);

CREATE TABLE IF NOT EXISTS track_likes (
  track_id BIGINT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
  user_id  BIGINT NOT NULL REFERENCES users(id),
  PRIMARY KEY (track_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_ledger_game     ON ledger(game_id, user_id);
CREATE INDEX IF NOT EXISTS idx_contracts_game  ON contracts(game_id, status);
CREATE INDEX IF NOT EXISTS idx_feed_game       ON feed(game_id, created_at);
CREATE INDEX IF NOT EXISTS idx_events_contract ON contract_events(contract_id);
`;

// Columns added after the first release. Each runs once on an existing database.
const MIGRATIONS = [
  'ALTER TABLE games ADD COLUMN IF NOT EXISTS uploads_open INTEGER NOT NULL DEFAULT 0',
];

/** Create or update the schema. Uses the direct (unpooled) URL, as Neon recommends for DDL. */
async function initDb() {
  const client = new Client({ connectionString: process.env.DATABASE_URL_UNPOOLED || DATABASE_URL, connectionTimeoutMillis: 15_000 });
  await client.connect();
  try {
    await client.query(SCHEMA);
    for (const sql of MIGRATIONS) await client.query(sql);
  } finally {
    await client.end();
  }
}

/** The game's SQL is written with `?` placeholders; Postgres wants $1, $2, … */
const converted = new Map();
function toPg(sql) {
  let out = converted.get(sql);
  if (out) return out;
  let n = 0;
  let quoted = false;
  out = '';
  for (const ch of sql) {
    if (ch === "'") quoted = !quoted;
    out += ch === '?' && !quoted ? `$${++n}` : ch;
  }
  converted.set(sql, out);
  return out;
}

// Inside tx(), every query runs on the transaction's own connection.
const txClient = new AsyncLocalStorage();
const query = (sql, params) => (txClient.getStore() || pool).query(toPg(sql), params);

/** All rows. */
const all = async (sql, ...params) => (await query(sql, params)).rows;
/** First row, or undefined. */
const get = async (sql, ...params) => (await query(sql, params)).rows[0];
/** Run a statement; returns the pg result (rowCount, and rows for RETURNING). */
const run = (sql, ...params) => query(sql, params);
/** Run several statements with no parameters. */
const exec = (sql) => (txClient.getStore() || pool).query(sql);

/**
 * Run fn inside a transaction; rolls back on throw. Writers take one shared
 * advisory lock so money moves one at a time (two offers can't both spend the
 * same cash), matching the single-writer behavior the game was built on.
 */
async function tx(fn) {
  if (txClient.getStore()) return fn();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(727274)');
    const result = await txClient.run(client, fn);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

module.exports = { pool, initDb, all, get, run, exec, tx, DATA_DIR, UPLOAD_DIR };
